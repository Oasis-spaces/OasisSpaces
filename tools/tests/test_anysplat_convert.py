"""AnySplat's prediction is aligned to the camera solve and converted to the
pipeline's splat without losing a gaussian's place, shape or opacity.

    python3 tools/tests/test_anysplat_convert.py      (or pytest tools/tests)
"""

import sys
import tempfile
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "pipeline"))
from splat_anysplat import choose_views, similarity, to_splat  # noqa: E402
from splat_tools import read_splat, write_splat  # noqa: E402

rng = np.random.default_rng(7)


def random_rotations(n):
    q = rng.normal(size=(n, 4))
    q /= np.linalg.norm(q, axis=1, keepdims=True)
    return rotation_from_quaternions(q)


def rotation_from_quaternions(q):
    """w x y z unit quaternions to matrices, the textbook formula."""
    w, x, y, z = q.T
    return np.stack([
        np.stack([1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)], -1),
        np.stack([2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)], -1),
        np.stack([2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)], -1),
    ], 1)


TURN = rotation_from_quaternions(np.array([[0.8, 0.2, -0.5, 0.26]]) / np.linalg.norm([0.8, 0.2, -0.5, 0.26]))[0]


def known_alignment():
    return 3.7, TURN, np.array([0.4, -1.2, 2.5])


def walk(views=12):
    """Solved cameras along a walk (camera-to-world), and the same cameras as a
    predictor with its own origin, orientation and scale would place them."""
    s, R, t = known_alignment()
    solved = np.tile(np.eye(4), (views, 1, 1))
    solved[:, :3, :3] = random_rotations(views)
    solved[:, :3, 3] = np.c_[np.linspace(0, 4, views), rng.normal(0, 0.3, views), rng.normal(0, 0.3, views)]
    predicted = solved.copy()
    predicted[:, :3, :3] = R.T @ solved[:, :3, :3]
    predicted[:, :3, 3] = (solved[:, :3, 3] - t) @ R / s
    return solved, predicted


def test_the_alignment_recovers_the_predictors_frame():
    s, R, t = known_alignment()
    solved, predicted = walk()
    fs, fR, ft, fit = similarity(predicted, solved)
    assert abs(fs - s) < 1e-9
    assert np.allclose(fR, R) and np.allclose(ft, t)
    assert fit["centre_misfit_median"] < 1e-9 and fit["direction_misfit_median_deg"] < 1e-6


def test_one_badly_placed_view_does_not_set_the_scale():
    s, _, _ = known_alignment()
    solved, predicted = walk()
    predicted[5, :3, 3] += [2.0, -1.0, 0.5]       # the predictor lost this view
    fs, _, _, fit = similarity(predicted, solved)
    assert abs(fs - s) < 1e-6
    assert fit["views_kept"] < fit["views"]
    assert fit["centre_misfit_median"] < 1e-6


def prediction(n=50):
    axes = random_rotations(n)
    sizes = rng.uniform(0.01, 0.2, (n, 3))
    return {"means": rng.normal(size=(n, 3)).astype(np.float32),
            "covariances": np.einsum("nij,nj,nkj->nik", axes, sizes ** 2, axes).astype(np.float32),
            "opacities": rng.uniform(0.01, 0.99, n).astype(np.float32),
            "dc": rng.normal(size=(n, 3)).astype(np.float32)}


def test_each_gaussian_moves_turns_and_grows_with_the_room():
    s, R, t = known_alignment()
    raw = prediction()
    out = to_splat(raw, s, R, t)
    means = np.c_[out["x"], out["y"], out["z"]]
    assert np.allclose(means, s * raw["means"].astype(np.float64) @ R.T + t, atol=1e-4)
    q = np.c_[out["rot_0"], out["rot_1"], out["rot_2"], out["rot_3"]].astype(np.float64)
    scales = np.exp(np.c_[out["scale_0"], out["scale_1"], out["scale_2"]].astype(np.float64))
    axes = rotation_from_quaternions(q / np.linalg.norm(q, axis=1, keepdims=True))
    rebuilt = np.einsum("nij,nj,nkj->nik", axes, scales ** 2, axes)
    expected = s * s * np.einsum("ij,njk,lk->nil", R, raw["covariances"].astype(np.float64), R)
    assert np.allclose(rebuilt, expected, rtol=1e-4, atol=1e-9)


def test_opacity_and_colour_are_stored_as_splat_files_keep_them():
    raw = prediction()
    out = to_splat(raw, 1.0, np.eye(3), np.zeros(3))
    assert np.allclose(1 / (1 + np.exp(-out["opacity"].astype(np.float64))), raw["opacities"], atol=1e-5)
    assert np.array_equal(np.c_[out["f_dc_0"], out["f_dc_1"], out["f_dc_2"]], raw["dc"])
    assert not any(out[f"f_rest_{k}"].any() for k in range(45))


def test_the_prediction_is_a_file_opensplat_resumes_from():
    out = to_splat(prediction(), 1.0, np.eye(3), np.zeros(3))
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "splat-anysplat-ff.ply"
        write_splat(path, out, comment="Generated by opensplat at iteration 0")
        header = path.read_bytes().split(b"end_header")[0]
        back, _ = read_splat(path)
    assert b"comment Generated by opensplat at iteration 0\n" in header
    assert np.array_equal(back, out)


def test_views_are_spread_along_the_walk():
    names = [f"frame_{i:05d}.jpg" for i in range(1, 101)]
    picked = choose_views(names[::-1], 24)
    assert len(picked) == 24 and picked == sorted(picked)
    assert picked[0] == names[0] and picked[-1] == names[-1]
    gaps = np.diff([names.index(p) for p in picked])
    assert gaps.max() - gaps.min() <= 1
    assert choose_views(names[:10], 24) == names[:10]


